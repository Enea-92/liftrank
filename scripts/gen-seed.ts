// Generates supabase/03_seed_exercises.sql from the exercise catalog in the app, so the app and the
// database always agree on exercise ids. Run:  npx tsx scripts/gen-seed.ts
import { writeFileSync } from 'fs';
import { join } from 'path';
import { EXERCISES } from '../src/data/exercises';

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;
const arr = (a: string[]) => `array[${a.map((x) => q(x.toLowerCase())).join(', ')}]::text[]`;

const values = EXERCISES.map(
  (e) =>
    `  (${q(e.id)}, null, ${q(e.name)}, ${q(e.muscle.toLowerCase())}, ${arr(e.secondary)}, ${q(e.equipment)}, ${q(e.category)}, ${q(e.difficulty)}, ${q(e.tracking)}, ${q(e.instructions)}, ${e.ranked})`,
).join(',\n');

const sql = `-- GENERATED by scripts/gen-seed.ts from src/data/exercises.ts. Do not edit by hand.
-- Run after 02_full_schema.sql. Safe to re-run (updates existing rows).
insert into public.exercises
  (id, owner_id, name, primary_muscle, secondary_muscles, equipment, category, difficulty, tracking_type, instructions, is_ranked)
values
${values}
on conflict (id) do update set
  name = excluded.name,
  primary_muscle = excluded.primary_muscle,
  secondary_muscles = excluded.secondary_muscles,
  equipment = excluded.equipment,
  category = excluded.category,
  difficulty = excluded.difficulty,
  tracking_type = excluded.tracking_type,
  instructions = excluded.instructions,
  is_ranked = excluded.is_ranked;
`;
writeFileSync(join(__dirname, '..', 'supabase', '03_seed_exercises.sql'), sql);
console.log(`Wrote ${EXERCISES.length} exercises`);
